#!/usr/bin/env node
// #1084 AC-2: turns the tested `scripts/mcp-launch.mjs` into the inline
// `node -e <source>` form shipped in `.mcp.json`. A file-path launcher
// requires `${CLAUDE_PLUGIN_ROOT}` (or a `:-default`, which resolves to the
// open project, not the plugin root — see the QA probe on #1084) to locate
// it; inlining the source removes the placeholder entirely. Keeping
// mcp-launch.mjs as the source of truth means its existing unit and
// integration tests still cover the real launcher logic — this generator
// only reshapes it for `node -e`, which runs CommonJS by default (no
// `import`/`export`, no `import.meta`) and never sets argv[0] to a script
// path (so the pinned spec lands at argv[1], not argv[2]).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DEFAULT_SOURCE = join(__dirname, "mcp-launch.mjs");

const IMPORT_BLOCK = `import { spawn } from "node:child_process";
import {
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";`;

const REQUIRE_BLOCK = `const { spawn } = require("node:child_process");
const {
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmdirSync,
  rmSync,
  statSync,
  writeFileSync,
} = require("node:fs");
const { tmpdir } = require("node:os");
const { join } = require("node:path");`;

const MAIN_GUARD_BLOCK = `// Only run when invoked directly (\`node mcp-launch.mjs ...\`), not when
// imported — lets tests exercise resolveNpxCommand() without triggering the
// spawn side effects above. Compare real paths: import.meta.url is always
// resolved, but Claude Code can start the plugin's copy through a symlinked
// path (a symlinked ~/.claude, macOS /var -> /private/var), and a plain
// string compare then skips main() and the server never starts.
const isMain = (() => {
  try {
    return (
      Boolean(process.argv[1]) &&
      realpathSync(process.argv[1]) ===
        realpathSync(fileURLToPath(import.meta.url))
    );
  } catch {
    return false;
  }
})();
if (isMain) {
  main();
}`;

/**
 * Generate the inline `node -e` launcher source from `scripts/mcp-launch.mjs`.
 * Throws if the source file's shape has drifted from what this generator
 * knows how to transform, rather than silently shipping a broken launcher.
 */
export function generateInlineLauncherSource(sourcePath = DEFAULT_SOURCE) {
  let src = readFileSync(sourcePath, "utf8");

  src = src.replace(/^#!.*\n/, "");

  if (!src.includes(IMPORT_BLOCK)) {
    throw new Error(
      "generate-mcp-launch-inline: import block shape changed in mcp-launch.mjs; update this generator",
    );
  }
  src = src.replace(IMPORT_BLOCK, REQUIRE_BLOCK);

  // `node -e` runs CommonJS: every `export function` becomes a plain
  // function. Anything else exported (const, default, re-exports) is a shape
  // this generator does not know how to inline, so refuse rather than ship it.
  src = src.replace(/^export function /gm, "function ");
  if (/^export\b/m.test(src)) {
    throw new Error(
      "generate-mcp-launch-inline: mcp-launch.mjs exports something other than `export function`; update this generator",
    );
  }

  if (!src.includes(MAIN_GUARD_BLOCK)) {
    throw new Error(
      "generate-mcp-launch-inline: isMain guard shape changed in mcp-launch.mjs; update this generator",
    );
  }
  src = src.replace(MAIN_GUARD_BLOCK, "main();");

  if (!src.includes("process.argv[2]")) {
    throw new Error(
      "generate-mcp-launch-inline: spec argv index changed in mcp-launch.mjs; update this generator",
    );
  }
  src = src.replaceAll("process.argv[2]", "process.argv[1]");

  // #1089: prepare-marketplace stamps the root .mcp.json with a global
  // `sequant@[^"\s]+` replace and the templates/mcp.json dist copy with a
  // `sequant@latest` replace. Any occurrence of that token inside the
  // launcher would be rewritten by the stamp and break every byte-identical
  // drift gate, so refuse to generate a source that contains it at all.
  if (/sequant@/.test(src)) {
    throw new Error(
      "generate-mcp-launch-inline: mcp-launch.mjs contains the package name followed by '@'; the release stamp would rewrite it",
    );
  }

  return src.trim();
}

/**
 * Render `src/lib/mcp-launch-inline.generated.ts` (#1089 D-1): the inline
 * source as a TS string constant, so runtime code (`getSequantMcpConfig`) can
 * embed it — `scripts/` is not in package.json `files`. `// prettier-ignore`
 * keeps a formatter from re-quoting the literal and dirtying the file.
 */
export function renderGeneratedModule(source) {
  return (
    "// GENERATED by scripts/generate-mcp-launch-inline.mjs --write (#1089).\n" +
    "// Do not edit: regenerate with `npm run mcp-launch:inline`. The source of\n" +
    "// truth is scripts/mcp-launch.mjs; the drift gate lives in\n" +
    "// scripts/plugin-mcp-pin.test.ts.\n" +
    "\n" +
    "// prettier-ignore\n" +
    "export const MCP_LAUNCHER_INLINE_SOURCE =\n" +
    "  " +
    JSON.stringify(source) +
    ";\n"
  );
}

/**
 * Replace args[1] of an inline `node -e` sequant entry in a JSON config file.
 * `pick` selects the entry from the parsed config (wrapped or flat shape).
 */
function rewriteInlineEntry(filePath, label, pick, source) {
  const config = JSON.parse(readFileSync(filePath, "utf8"));
  const entry = pick(config);
  if (!entry || entry.command !== "node" || entry.args?.[0] !== "-e") {
    throw new Error(
      `generate-mcp-launch-inline: ${label} sequant entry is not the inline \`node -e\` shape`,
    );
  }
  if (entry.args[1] === source) {
    process.stderr.write(`mcp-launch:inline: ${label} already up to date\n`);
  } else {
    entry.args[1] = source;
    writeFileSync(filePath, JSON.stringify(config, null, 2) + "\n");
    process.stderr.write(`mcp-launch:inline: rewrote ${label} args[1]\n`);
  }
}

/**
 * #1265: plugin/.mcp.json is used only as the plugin's MCP config. Unlike
 * root .mcp.json, it is never loaded as a project config, so
 * `${CLAUDE_PLUGIN_ROOT}` is always defined there and it can run a launcher
 * file the plugin ships. The directory refuses the inline `node -e` form
 * (a command over 1,024 parts isn't checked). Copy scripts/mcp-launch.mjs
 * into plugin/ and check the entry points at it.
 */
export const PLUGIN_LAUNCHER_ARG = "${CLAUDE_PLUGIN_ROOT}/mcp-launch.mjs";

function syncPluginLauncherFile(root) {
  const from = join(root, "scripts", "mcp-launch.mjs");
  const to = join(root, "plugin", "mcp-launch.mjs");
  const want = readFileSync(from, "utf8");
  let have;
  try {
    have = readFileSync(to, "utf8");
  } catch {
    have = undefined;
  }
  if (have === want) {
    process.stderr.write("mcp-launch:inline: plugin/mcp-launch.mjs already up to date\n");
  } else {
    writeFileSync(to, want);
    process.stderr.write("mcp-launch:inline: synced plugin/mcp-launch.mjs\n");
  }
  const config = JSON.parse(
    readFileSync(join(root, "plugin", ".mcp.json"), "utf8"),
  );
  const entry = config.mcpServers?.sequant;
  if (
    !entry ||
    entry.command !== "node" ||
    entry.args?.[0] !== PLUGIN_LAUNCHER_ARG ||
    entry.args.length !== 2
  ) {
    throw new Error(
      "generate-mcp-launch-inline: plugin/.mcp.json sequant entry must be `node " +
        PLUGIN_LAUNCHER_ARG +
        " sequant@<version>`",
    );
  }
}

const isMain =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const source = generateInlineLauncherSource();
  if (process.argv.includes("--write")) {
    // `npm run mcp-launch:inline` — also the first step of prepare:marketplace,
    // so a release can never ship a launcher that drifted from mcp-launch.mjs.
    // Rewrites root .mcp.json (#1084; this repo's own project config),
    // templates/mcp.json, and the generated TS module that
    // getSequantMcpConfig() embeds (#1089). The shipped plugin/.mcp.json
    // (#1265) runs a launcher *file* instead, so it's synced, not inlined.
    const root = join(__dirname, "..");
    rewriteInlineEntry(
      join(root, ".mcp.json"),
      ".mcp.json",
      (c) => c.mcpServers?.sequant,
      source,
    );
    syncPluginLauncherFile(root);
    rewriteInlineEntry(
      join(root, "templates", "mcp.json"),
      "templates/mcp.json",
      (c) => c.sequant,
      source,
    );
    const modulePath = join(
      root,
      "src",
      "lib",
      "mcp-launch-inline.generated.ts",
    );
    const moduleText = renderGeneratedModule(source);
    let current;
    try {
      current = readFileSync(modulePath, "utf8");
    } catch {
      current = undefined;
    }
    if (current === moduleText) {
      process.stderr.write(
        "mcp-launch:inline: src/lib/mcp-launch-inline.generated.ts already up to date\n",
      );
    } else {
      writeFileSync(modulePath, moduleText);
      process.stderr.write(
        "mcp-launch:inline: wrote src/lib/mcp-launch-inline.generated.ts\n",
      );
    }
  } else {
    process.stdout.write(source + "\n");
  }
}
